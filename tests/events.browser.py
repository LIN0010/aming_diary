"""活動完整操作、保存、單頁導覽及手機檢查：python tests/events.browser.py。"""
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from threading import Thread
import os, shutil
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[1]
class Quiet(SimpleHTTPRequestHandler):
 def log_message(self,*_): pass
server=ThreadingHTTPServer(('127.0.0.1',0),partial(Quiet,directory=str(ROOT/'aming-game')))
Thread(target=server.serve_forever,daemon=True).start()
BASE=f'http://127.0.0.1:{server.server_port}/'
errors=[]
def ready(page):
 expect(page.locator('#event-screen')).to_be_visible(timeout=20000)
 expect(page.locator('#ev-content h2').first).to_be_visible()
 expect(page.locator('[data-destination="event"]')).to_have_attribute('aria-current','page')
def shoot(page,title):
 page.locator('#ev-photo-file').set_input_files(str(ROOT/'aming-game/images/cow.png'))
 expect(page.locator('.ev-upload-preview')).to_be_visible()
 page.locator('#ev-photo-title').fill(title)
 page.locator('#ev-photo-description').fill('沿著春風，看見花開。')
 page.locator('#ev-submit-photo').click()
def nav(page,name):
 page.locator(f'[data-destination="{name}"]').click()
 expect(page.locator(f'#{name}-screen')).to_be_visible(timeout=20000)
try:
 with sync_playwright() as p:
  browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH') or shutil.which('chromium'),headless=True,args=['--no-sandbox'])
  context=browser.new_context(viewport={'width':1280,'height':900})
  page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
  page.goto(BASE+'game.html#/home')
  expect(page.locator('#home-screen')).to_be_visible(timeout=20000)
  page.evaluate("GameProgress.completeRuisui();GameProgress.saveNote('ruisui','活動不影響的主線心得');window.token='same-document'")
  main=page.evaluate("localStorage.getItem('aming-diary-progress')")
  nav(page,'event');ready(page)
  assert page.evaluate('window.token')=='same-document'
  assert 'demo' not in page.locator('#event-screen').inner_text().lower()
  assert page.locator('.ev-scroll').evaluate('(e)=>Math.abs(e.getBoundingClientRect().right-innerWidth)<1')
  assert page.locator('.ev-scroll').evaluate('(e)=>getComputedStyle(e).scrollbarWidth')=='thin'
  before_scroll=page.locator('.ev-scroll').evaluate('(e)=>e.scrollTop')
  page.locator('.ev-scroll').evaluate('(e)=>e.scrollTop=200')
  assert page.locator('.ev-scroll').evaluate('(e)=>e.scrollTop')>before_scroll
  page.locator('.ev-scroll').evaluate('(e)=>e.scrollTop=0')
  expect(page.locator('.ev-data-note')).to_contain_text('尚未連線')
  page.locator('#ev-tab-race').click()
  expect(page.locator('#ev-cards')).to_contain_text('鐵道旅行陣營戰')
  page.locator('#ev-tab-race').press('ArrowLeft')
  expect(page.locator('#ev-tab-photo')).to_have_attribute('aria-selected','true')
  page.locator('[data-action="open-photo"]').first.click()
  page.locator('.ev-rules summary').click()
  expect(page.locator('.ev-rules')).to_have_attribute('open','')
  expect(page.locator('#ev-submit-photo')).to_be_disabled()
  page.locator('[data-action="join-photo"]').click()
  page.locator('#ev-photo-file').set_input_files({'name':'not-photo.txt','mimeType':'text/plain','buffer':b'not an image'})
  expect(page.locator('#ev-message')).to_contain_text('請選擇')
  expect(page.locator('#ev-submit-photo')).to_be_disabled()
  for index,name in enumerate(['春風','<img src=x onerror=alert(1)>','月台邊的春天'],start=8):
   shoot(page,name)
   expect(page.locator('#ev-photo-count')).to_contain_text(str(index))
  expect(page.locator('.ev-photo-wall .ev-polaroid')).to_have_count(6)
  expect(page.locator('[data-claim="collection"]')).to_be_enabled()
  page.locator('[data-claim="collection"]').click()
  expect(page.locator('[data-claim="collection"]')).to_have_text('已領取')
  page.locator('.ev-polaroid').first.click()
  expect(page.locator('#ev-lightbox')).to_be_visible()
  expect(page.locator('#ev-lightbox-image img')).to_have_count(1)
  page.keyboard.press('Escape')
  expect(page.locator('#ev-lightbox')).not_to_be_visible()
  page.reload();ready(page)
  assert 'demo' not in page.locator('#event-screen').inner_text().lower()
  expect(page.locator('#ev-photo-count')).to_contain_text('10')
  expect(page.locator('[data-claim="collection"]')).to_have_text('已領取')
  assert page.evaluate("localStorage.getItem('aming-diary-progress')")==main
  print('PASS: 第四項導覽與頁籤、規則、三次實際圖片投稿、合作門檻、領獎、放大、重載保存及文字跳脫。',flush=True)
  page.locator('[data-action="back"]').click()
  page.go_back();expect(page.locator('#ev-photo-count')).to_be_visible()
  page.go_forward();expect(page.locator('#ev-tab-race')).to_be_visible()
  page.locator('#ev-tab-race').click()
  page.locator('[data-action="open-race"]').click()
  for i in range(3): page.locator(f'input[name="ev-answer-{i}"][value="0"]').check()
  page.locator('#ev-quiz button[type="submit"]').click()
  expect(page.locator('#ev-team-result')).to_contain_text('逐風列車')
  assert 'demo' not in page.locator('#event-screen').inner_text().lower()
  expect(page.locator('#ev-quiz')).to_have_count(0)
  expect(page.locator('#ev-team-result')).to_have_class('ev-team-result ev-reveal')
  expect(page.locator('#ev-leader')).to_contain_text('拾光月台')
  page.locator('[data-claim="participation"]').click()
  expect(page.locator('[data-claim="participation"]')).to_have_text('已領取')
  page.locator('[data-task="ticket"]').click()
  page.locator('#ev-direction').select_option('west')
  page.locator('[data-task="compass"]').click()
  expect(page.locator('#ev-personal-score')).to_contain_text('30')
  page.locator('#ev-direction').select_option('east')
  page.locator('[data-task="compass"]').click()
  expect(page.locator('#ev-leader')).to_contain_text('平手')
  page.locator('#ev-postcard').fill('祝所有旅人都能遇見自己的好風景')
  page.locator('[data-task="postcard"]').click()
  expect(page.locator('#ev-personal-score')).to_contain_text('160')
  expect(page.locator('[data-team-score="blue"]')).to_have_text('420')
  expect(page.locator('#ev-leader')).to_contain_text('逐風列車')
  expect(page.locator('[data-claim="personal"]')).to_be_enabled()
  expect(page.locator('[data-claim="winner"]')).to_be_disabled()
  page.locator('[data-claim="personal"]').click()
  page.reload();ready(page)
  expect(page.locator('#ev-personal-score')).to_contain_text('160')
  expect(page.locator('#ev-quiz')).to_have_count(0)
  expect(page.locator('[data-task="ticket"]')).to_be_disabled()
  assert page.evaluate("localStorage.getItem('aming-diary-progress')")==main
  print('PASS: 完成測驗固定分隊、三種特殊任務、失敗不加分、同步貢獻、追平與反超、參與／個人獎及重載防刷分。',flush=True)
  page.evaluate("""() => {
   const key=EventConfig.storageKey,s=JSON.parse(localStorage.getItem(key));
   s.clockStartedAt-=12*86400000;localStorage.setItem(key,JSON.stringify(s));EventStore.refresh();
  }""")
  expect(page.locator('[data-claim="winner"]')).to_be_enabled()
  page.locator('[data-claim="winner"]').click()
  expect(page.locator('[data-claim="winner"]')).to_have_text('已領取')
  page.once('dialog',lambda d:d.accept())
  page.locator('#ev-reset').click()
  expect(page.locator('#ev-quiz')).to_have_count(1)
  assert page.evaluate('EventStore.snapshot().photos.length')==0
  assert page.evaluate("localStorage.getItem('aming-diary-progress')")==main
  print('PASS: 活動結束後開放勝方獎勵；Demo 重置清除活動資料且保留主線。',flush=True)
  # 卸載活動後不保留視窗回呼或倒數工作；再進來仍可操作。
  nav(page,'home')
  page.locator('#aming-click-area').click()
  expect(page.locator('#aming-dialogue')).to_have_class('aming-dialogue show')
  nav(page,'event');ready(page)
  expect(page.locator('[data-game-nav]')).to_have_count(1)
  context.close()
  for width in (320,390):
   context=browser.new_context(viewport={'width':width,'height':844},is_mobile=True,has_touch=True)
   page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
   page.goto(BASE+'event.html');ready(page)
   page.locator('[data-action="open-photo"]').first.tap()
   page.locator('[data-action="join-photo"]').tap()
   shoot(page,f'{width} 的花季照片')
   expect(page.locator('#ev-photo-count')).to_contain_text('8')
   page.locator('[data-action="back"]').tap()
   page.locator('#ev-tab-race').tap()
   page.locator('[data-action="open-race"]').tap()
   for i in range(3): page.locator(f'input[name="ev-answer-{i}"][value="1"]').check()
   page.locator('#ev-quiz button[type="submit"]').tap()
   expect(page.locator('#ev-team-result')).to_contain_text('拾光月台')
   assert page.evaluate("document.getElementById('event-screen').scrollWidth <= innerWidth")
   assert page.locator('.ev-scroll').evaluate('(e)=>e.scrollWidth<=e.clientWidth')
   context.close()
  print('PASS: 320／390 手機可完整投稿與分隊，獨立頁面可用，畫面無水平溢出。',flush=True)
  context=browser.new_context()
  context.add_init_script("""window.failEventWrites=false;const write=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(window.failEventWrites&&k==='aming-diary-events-demo-v1')throw new DOMException('full','QuotaExceededError');return write.call(this,k,v);};""")
  page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
  page.goto(BASE+'event.html?activity=photo');ready(page)
  page.locator('[data-action="join-photo"]').click()
  page.evaluate('window.failEventWrites=true')
  shoot(page,'尚未成功的照片')
  expect(page.locator('#ev-photo-count')).to_contain_text('7')
  expect(page.locator('#ev-storage-warning')).to_be_visible()
  expect(page.locator('.ev-upload-preview')).to_be_visible()
  page.evaluate('window.failEventWrites=false')
  page.locator('#ev-submit-photo').click()
  expect(page.locator('#ev-photo-count')).to_contain_text('8')
  assert not errors,errors
  print('PASS: 儲存空間不足不虛報投稿成功，預覽與文字保留，可恢復後重試；無 JavaScript 錯誤。',flush=True)
  browser.close()
finally: server.shutdown()
